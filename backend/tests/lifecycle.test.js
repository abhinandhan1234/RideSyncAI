import {test} from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import mongoose from 'mongoose';
import bcrypt from 'bcryptjs';
import app from '../src/app.js';
import {User,Driver,Ride,RideOffer,Zone} from '../src/models/index.js';
import {expireOffers} from '../src/services/matching/dispatch.js';
import {attachSockets} from '../src/sockets/index.js';

const uri=process.env.TEST_MONGODB_URI;
test('MongoDB booking, rejection, reassignment, acceptance, completion and failures', {skip:!uri}, async()=>{
 const database=new URL(uri).pathname.slice(1);
 assert.equal(database,'ridesync_belagavi_test','Tests require the isolated database');
 process.env.JWT_SECRET ||= 'local-test-secret-that-is-at-least-32-characters';
 process.env.OFFER_TIMEOUT_MS='20000';
 await mongoose.connect(uri);
 const server=http.createServer(app);
 const io=attachSockets(server,app);
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin=`http://127.0.0.1:${server.address().port}`;
 const tag=`integration-${Date.now()}-${Math.random().toString(36).slice(2)}`;
 const point=(lng,lat)=>({type:'Point',coordinates:[lng,lat]});
 const request=async(path,method='GET',body,token)=>{const response=await fetch(origin+path,{method,headers:{'content-type':'application/json',...(token?{authorization:`Bearer ${token}`}:{})},body:body===undefined?undefined:JSON.stringify(body)});return {status:response.status,data:await response.json()};};
 const wait=async(fn)=>{for(let i=0;i<100;i++){const result=await fn();if(result)return result;await new Promise(resolve=>setTimeout(resolve,25));}throw new Error('Timed out waiting for dispatch');};
 const connectSocket=token=>new Promise((resolve,reject)=>{const ws=new WebSocket(origin.replace('http','ws')+'/socket.io/?EIO=4&transport=websocket');const frames=[];const timer=setTimeout(()=>reject(new Error('Socket handshake timeout')),3000);ws.onmessage=({data})=>{frames.push(data);if(data.startsWith('0{'))ws.send('40'+JSON.stringify({token}));if(data.startsWith('40{')||data.startsWith('44{')){clearTimeout(timer);resolve({ws,frames});}};ws.onerror=reject;});
 try{
  await Promise.all([Zone.init(),Driver.init(),RideOffer.init()]);
  const priorUsers=await User.find({email:/^(p|second)-integration-.*@example\.invalid$/}).select('_id');
  const priorRides=await Ride.find({passengerId:{$in:priorUsers.map(u=>u._id)},source:'LIVE',status:{$in:['REQUESTED','OFFERED','REASSIGNING','ACCEPTED','ARRIVING','ONGOING']}}).select('_id');
  await Ride.updateMany({_id:{$in:priorRides.map(r=>r._id)}},{$set:{status:'CANCELLED',cancelledAt:new Date()}});
  await RideOffer.updateMany({rideId:{$in:priorRides.map(r=>r._id)},status:'PENDING'},{$set:{status:'CANCELLED'}});
  await Driver.updateMany({externalId:/^TEST-integration-/},{$set:{status:'OFFLINE',activeRideId:null}});
  await Zone.updateOne({code:'Z01'},{$setOnInsert:{code:'Z01',name:'Fictional Test Zone',center:point(74.5,15.85)}},{upsert:true});
  const password=`test-${tag}`;
  const hash=await bcrypt.hash(password,8);
  const users=await User.create([{displayName:'Test Driver A',email:`a-${tag}@example.invalid`,passwordHash:hash,role:'DRIVER',isSynthetic:true},{displayName:'Test Driver B',email:`b-${tag}@example.invalid`,passwordHash:hash,role:'DRIVER',isSynthetic:true}]);
  const drivers=await Driver.create(users.map((user,i)=>({userId:user._id,externalId:`TEST-${tag}-${i}`,location:point(74.5001+i*.003,15.85),zoneCode:'Z01',status:'AVAILABLE',activeRideId:null,vehicle:{type:'CAR',capacity:4,plate:`TEST-${i}`},idleSince:new Date(Date.now()-3600000),acceptanceRate:.9,currentWorkload:0})));
  const registered=await request('/api/auth/register','POST',{name:'Test Passenger',email:`p-${tag}@example.invalid`,password,role:'passenger'});
  assert.equal(registered.status,201);
  const passenger=(await request('/api/auth/login','POST',{email:`p-${tag}@example.invalid`,password})).data.accessToken;
  const a=(await request('/api/auth/login','POST',{email:users[0].email,password})).data.accessToken;
  const b=(await request('/api/auth/login','POST',{email:users[1].email,password})).data.accessToken;
  assert.ok(passenger&&a&&b);
  const passengerSocket=await connectSocket(passenger);
  const driverSocket=await connectSocket(a);
  const deniedSocket=await connectSocket('invalid-token');
  assert.ok(deniedSocket.frames.some(frame=>frame.startsWith('44{')));
  deniedSocket.ws.close();
  const near=await request('/api/drivers/nearby?lng=74.5&lat=15.85', 'GET',undefined,passenger);
  assert.equal(near.data.count,2);
  assert.equal((await request('/api/drivers/nearby?lng=181&lat=15.85','GET',undefined,passenger)).status,400);
  assert.equal((await request('/api/drivers/nearby?lng=74.5&lat=15.85')).status,401);
  const payload={pickup:point(74.5,15.85),dropoff:point(74.51,15.86),routeType:'eco'};
  const created=await request('/api/rides','POST',payload,passenger);
  assert.equal(created.status,202);
  const rideId=created.data.rideId;
  const first=await wait(()=>RideOffer.findOne({rideId,attempt:1}));
  await wait(()=>driverSocket.frames.some(frame=>frame.includes('ride:offer')));
  passengerSocket.ws.send('42'+JSON.stringify(['ride:join',rideId]));
  await wait(()=>io.of('/').adapter.rooms.has(`ride:${rideId}`));
  assert.equal(String(first.driverId),String(drivers[0]._id));
  const wrong=await request(`/api/offers/${first.id}/respond`,'POST',{action:'accept'},b);
  assert.equal(wrong.status,403);
  assert.equal((await request(`/api/rides/${rideId}/offers/${first.id}/respond`,'POST',{action:'reject'},a)).status,200);
  await wait(()=>passengerSocket.frames.some(frame=>frame.includes('ride:rejected')));
  const second=await wait(()=>RideOffer.findOne({rideId,attempt:2}));
  assert.equal(String(second.driverId),String(drivers[1]._id));
  const concurrentAcceptance=await Promise.all([
   request(`/api/offers/${second.id}/respond`,'POST',{action:'accept'},b),
   request(`/api/offers/${second.id}/respond`,'POST',{action:'accept'},b),
  ]);
  assert.deepEqual(concurrentAcceptance.map(result=>result.status).sort(),[200,409]);
  await wait(()=>passengerSocket.frames.some(frame=>frame.includes('ride:accepted')));
  assert.equal((await request(`/api/offers/${second.id}/respond`,'POST',{action:'accept'},b)).status,409);
  for(const status of ['ARRIVING','ONGOING','COMPLETED'])assert.equal((await request(`/api/rides/${rideId}/status`,'PATCH',{status},b)).status,200);
  await wait(()=>passengerSocket.frames.some(frame=>frame.includes('ride:status')));
  assert.equal((await Ride.findById(rideId)).status,'COMPLETED');
  console.log('Verified booking response',JSON.stringify(created.data));
  console.log('Verified completed ride',JSON.stringify({rideId,status:(await Ride.findById(rideId)).status,finalFare:(await Ride.findById(rideId)).fare?.total,driverAvailable:(await Driver.findById(drivers[1]._id)).status==='AVAILABLE'}));
  assert.equal((await Driver.findById(drivers[1]._id)).status,'AVAILABLE');
  assert.ok((await request('/api/rides/history','GET',undefined,passenger)).data.rides.some(ride=>String(ride._id)===rideId));
  assert.equal((await request(`/api/rides/${rideId}/status`,'PATCH',{status:'ARRIVING'},b)).status,409);
  const noDrivers=await request('/api/rides','POST',payload,passenger);
  assert.equal(noDrivers.status,202);
  const competing=await request('/api/rides','POST',payload,passenger);
  assert.equal(competing.status,409);
  await wait(async()=>['OFFERED','FAILED'].includes((await Ride.findById(noDrivers.data.rideId)).status));
  assert.equal((await request(`/api/rides/${noDrivers.data.rideId}/cancel`,'POST',{},passenger)).status,200);
  assert.equal((await Ride.findById(noDrivers.data.rideId)).status,'CANCELLED');
  assert.equal((await request('/api/rides','POST',{...payload,pickup:point(181,15.85)},passenger)).status,400);
  const expiring=await request('/api/rides','POST',payload,passenger);
  const expiringOffer=await wait(()=>RideOffer.findOne({rideId:expiring.data.rideId,attempt:1}));
  await RideOffer.updateOne({_id:expiringOffer._id},{$set:{expiresAt:new Date(Date.now()-1000)}});
  await expireOffers();
  assert.equal((await RideOffer.findById(expiringOffer._id)).status,'EXPIRED');
  assert.ok(await RideOffer.exists({rideId:expiring.data.rideId,attempt:2}));
  await request(`/api/rides/${expiring.data.rideId}/cancel`,'POST',{},passenger);
  await Driver.updateMany({_id:{$in:drivers.map(d=>d._id)}},{$set:{status:'OFFLINE',activeRideId:null}});
  await Driver.updateOne({_id:drivers[0]._id},{$set:{status:'AVAILABLE'}});
  const other=await request('/api/auth/register','POST',{name:'Second Passenger',email:`second-${tag}@example.invalid`,password});
  const otherToken=other.data.accessToken;
  const otherSocket=await connectSocket(otherToken);
  otherSocket.ws.send('42'+JSON.stringify(['ride:join',rideId]));
  await new Promise(resolve=>setTimeout(resolve,50));
  io.to(`ride:${rideId}`).emit('ride:status',{marker:'private-ride-check'});
  await wait(()=>passengerSocket.frames.some(frame=>frame.includes('private-ride-check')));
  assert.equal(otherSocket.frames.some(frame=>frame.includes('private-ride-check')),false);
  otherSocket.ws.close();
  const [firstBooking,secondBooking]=await Promise.all([request('/api/rides','POST',payload,passenger),request('/api/rides','POST',payload,otherToken)]);
  assert.equal(firstBooking.status,202);
  assert.equal(secondBooking.status,202);
  await wait(async()=>{
   const rides=await Ride.find({_id:{$in:[firstBooking.data.rideId,secondBooking.data.rideId]}});
   return rides.every(ride=>['OFFERED','FAILED'].includes(ride.status));
  });
  const contenders=await Ride.find({_id:{$in:[firstBooking.data.rideId,secondBooking.data.rideId]}});
  assert.equal(contenders.filter(ride=>ride.status==='OFFERED').length,1);
  assert.equal(contenders.filter(ride=>ride.status==='FAILED').length,1);
  assert.equal((await Driver.findById(drivers[0]._id)).status,'RESERVED');
  passengerSocket.ws.close();driverSocket.ws.close();
 }finally{await new Promise(resolve=>io.close(resolve));await new Promise(resolve=>server.close(resolve));await mongoose.disconnect();}
});
